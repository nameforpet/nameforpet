const DISPOSABLE_DOMAINS = new Set(DISPOSABLE_DOMAINS_LIST);

/**
 * Checks whether an email address belongs to a disposable, temporary, or burner email provider.
 */
export function isDisposableEmail(email: string): { isDisposable: boolean; domain?: string; reason?: string } {
  if (!email || typeof email !== 'string') {
    return { isDisposable: false };
  }

  const clean = email.trim().toLowerCase();
  const parts = clean.split('@');
  if (parts.length !== 2) {
    return { isDisposable: true, reason: 'Invalid email address format' };
  }

  const domain = parts[1].trim();

  // 1. Direct domain match
  if (DISPOSABLE_DOMAINS.has(domain)) {
    return {
      isDisposable: true,
      domain,
      reason: `Temporary/disposable email domain "${domain}" is not permitted.`
    };
  }

  // 2. Subdomain check (e.g. *.mailinator.com, *.guerrillamail.com)
  for (const banned of DISPOSABLE_DOMAINS_LIST) {
    if (domain.endsWith('.' + banned)) {
      return {
        isDisposable: true,
        domain,
        reason: `Temporary/disposable email provider (*.${banned}) is not permitted.`
      };
    }
  }

  // 3. Heuristic / Pattern checks for suspicious temp mail patterns
  const suspiciousPrefixes = [
    'tempmail', '10min', 'disposable', 'trashmail', 'fakeinbox',
    'guerrilla', 'mailinator', 'throwaway', 'burnermail', 'dropmail',
    'getnada', 'mohmal', 'sharklasers'
  ];

  for (const prefix of suspiciousPrefixes) {
    if (domain.startsWith(prefix) && (domain.includes('.com') || domain.includes('.org') || domain.includes('.net') || domain.includes('.io'))) {
      return {
        isDisposable: true,
        domain,
        reason: `Temporary email service (${domain}) is not permitted.`
      };
    }
  }

  return { isDisposable: false, domain };
}
